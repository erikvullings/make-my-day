const translators: Record<string, (key: string) => string> = {};

export function getTranslator(lang: string): (key: string) => string {
  const langKey = lang.toLowerCase();
  
  if (!translators[langKey]) {
    const langMessages = messages[langKey] || messages.en;
    translators[langKey] = translate(langMessages);
  }
  
  return translators[langKey];
}

export function getAvailableLanguages(): string[] {
  return Object.keys(messages);
}
